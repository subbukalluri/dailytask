/**
 * Task 1: Hello Java
 * A first Java program demonstrating the basic file structure:
 *  - The public class name must match the filename (HelloJava.java -> class HelloJava).
 *  - The main method (public static void main(String[] args)) is the entry point
 *    the JVM looks for and runs first when the program starts.
 *  - System.out.println(...) writes text to the console followed by a newline.
 */
public class HelloJava {
    public static void main(String[] args) {
        System.out.println("Welcome to Java!");
        System.out.println("This is my first step into Java programming.");
    }
}
